"""
Unit tests for all 10 video and audio containers, codecs, bitrates,
and command-line arguments generated by the backend.
"""
import pytest
from app import (
    CONTAINER_METADATA,
    build_download_command,
    DownloadJobRequest,
    get_base_dir,
)
from pathlib import Path


def test_all_10_containers_defined():
    """Verify that all 10 advertised containers & encodings exist in metadata."""
    expected_containers = [
        # 5 Video formats
        "mp4-h264",
        "mp4-av1",
        "mkv",
        "webm",
        "mov",
        # 5 Audio formats
        "mp3",
        "m4a",
        "opus",
        "flac",
        "wav",
    ]
    for container in expected_containers:
        assert container in CONTAINER_METADATA, f"Container {container} missing from CONTAINER_METADATA"
        meta = CONTAINER_METADATA[container]
        assert "title" in meta
        assert "category" in meta
        assert meta["category"] in ["video", "audio"]


@pytest.mark.parametrize("container", ["mp4-h264", "mp4-av1", "mkv", "webm", "mov"])
def test_video_codec_commands(container):
    """Verify build_download_command generates valid yt-dlp arguments for every video container."""
    output_dir = Path("/tmp/yt_test_output")
    req = DownloadJobRequest(
        url="https://www.youtube.com/watch?v=dQw4w9WgXcQ",
        output_dir=str(output_dir),
        quality="1080p",
        container=container,
        audio_only=False,
    )
    cmd = build_download_command(req, output_dir=output_dir)
    assert isinstance(cmd, list)
    assert cmd[0] == "yt-dlp"
    assert req.url in cmd

    # Verify container-specific flags
    cmd_str = " ".join(cmd)
    if container == "mp4-h264":
        assert "--merge-output-format" in cmd
        assert "mp4" in cmd
        assert "avc" in cmd_str or "h264" in cmd_str
    elif container == "mp4-av1":
        assert "--merge-output-format" in cmd
        assert "mp4" in cmd
        assert "av01" in cmd_str
    elif container == "mkv":
        assert "--merge-output-format" in cmd
        assert "mkv" in cmd
    elif container == "webm":
        assert "--merge-output-format" in cmd
        assert "webm" in cmd
        assert "vp9" in cmd_str
    elif container == "mov":
        assert "--merge-output-format" in cmd
        assert "mov" in cmd


@pytest.mark.parametrize("audio_fmt", ["mp3", "m4a", "flac", "wav", "opus"])
def test_audio_codec_commands(audio_fmt):
    """Verify build_download_command generates valid audio extraction flags for every audio format."""
    output_dir = Path("/tmp/yt_test_output")
    req = DownloadJobRequest(
        url="https://www.youtube.com/watch?v=dQw4w9WgXcQ",
        output_dir=str(output_dir),
        quality="audio",
        container=audio_fmt,
        audio_only=True,
        audio_format=audio_fmt,
    )
    cmd = build_download_command(req, output_dir=output_dir)
    assert isinstance(cmd, list)
    assert cmd[0] == "yt-dlp"
    assert "-x" in cmd or "--extract-audio" in cmd
    assert "--audio-format" in cmd
    fmt_idx = cmd.index("--audio-format")
    assert cmd[fmt_idx + 1] == audio_fmt

    if audio_fmt == "mp3":
        assert "--audio-quality" in cmd
        q_idx = cmd.index("--audio-quality")
        assert cmd[q_idx + 1] == "0"


def test_optional_features_flags():
    """Verify chapter embedding, subtitles, and sponsorblock flags in command builder."""
    output_dir = Path("/tmp/yt_test_output")
    req = DownloadJobRequest(
        url="https://www.youtube.com/watch?v=dQw4w9WgXcQ",
        output_dir=str(output_dir),
        quality="1080p",
        container="mp4-h264",
        embed_subs=True,
        embed_thumbnail=True,
        embed_chapters=True,
        sponsorblock=True,
    )
    cmd = build_download_command(req, output_dir=output_dir)
    assert "--write-subs" in cmd or "--write-auto-subs" in cmd
    assert "--embed-thumbnail" in cmd
    assert "--embed-chapters" in cmd
    assert "--sponsorblock-remove" in cmd
